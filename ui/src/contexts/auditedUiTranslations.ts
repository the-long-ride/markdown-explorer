type ExtendedAuditedUiTranslationDomains = Omit<AuditedUiTranslationDomains, 'rendererUi'> & {
  readonly insights: InsightsTranslations;
  readonly rendererUi: AuditedUiTranslationDomains['rendererUi'] & {
    readonly wikiTransclusionCycle: string;
    readonly wikiTransclusionDepth: string;
    readonly wikiLinkAmbiguous: string;
  };
};

export const AUDITED_UI_TRANSLATIONS = Object.fromEntries(
  (Object.keys(SOURCE_AUDITED_UI_TRANSLATIONS) as AppLanguage[]).map((language) => {
    const base = SOURCE_AUDITED_UI_TRANSLATIONS[language];
    return [language, {
      ...base,
      insights: INSIGHTS_TRANSLATIONS[language],
      rendererUi: {
        ...base.rendererUi,
        ...WIKI_RENDERER_TRANSLATIONS[language],
      },
    }];
  }),
) as Record<AppLanguage, ExtendedAuditedUiTranslationDomains>;
